#!/usr/bin/env python3
"""Generate Simplified Chinese aliases for the English spell and aura names
the addon looks up.

Discovery scans the learned spellbook and compares client-provided names, so a
zhCN client needs the Chinese spelling of every catalog name. This reads the
Forever client's own SpellName tables (enUS and zhCN, one shared ID space) from
wago.tools, finds every quoted string in the addon that is an English spell
name, and writes the distinct Chinese spellings to SpellAliases.lua. Only names
are written, never spell IDs, so discovery still depends on what the player
has actually learned.

    python3 scripts/import_spell_names.py [--build 1.60.1.70888] [--cache DIR]
"""
from __future__ import annotations

import argparse
import csv
import io
import re
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
ADDON = ROOT / 'addons' / 'ForeverUtilities'
OUTPUT = ADDON / 'SpellAliases.lua'
SKIP = {'Locale.lua', 'SpellAliases.lua'}
URL = 'https://wago.tools/db2/SpellName/csv?build={build}&locale={locale}'


def table(build: str, locale: str, cache: Path | None) -> dict[str, str]:
    path = cache / f'SpellName_{locale}.csv' if cache else None
    if path and path.exists():
        text = path.read_text(encoding='utf-8')
    else:
        request = urllib.request.Request(URL.format(build=build, locale=locale),
                                         headers={'User-Agent': 'spell-alias-import'})
        with urllib.request.urlopen(request, timeout=120) as response:
            text = response.read().decode('utf-8')
        if path:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text, encoding='utf-8')
    rows = csv.reader(io.StringIO(text))
    next(rows)
    return {row[0]: row[1] for row in rows if len(row) >= 2}


def lua_strings(code: str):
    """Yield the quoted string literals of Lua source, skipping comments and
    long brackets, so an apostrophe in a comment never pairs with a quote."""
    i, n = 0, len(code)
    while i < n:
        if code.startswith('--', i):
            long = re.match(r'--\[(=*)\[', code[i:])
            if long:
                close = ']' + long.group(1) + ']'
                j = code.find(close, i)
                i = n if j < 0 else j + len(close)
            else:
                j = code.find('\n', i)
                i = n if j < 0 else j
            continue
        long = re.match(r'\[(=*)\[', code[i:])
        if long:
            close = ']' + long.group(1) + ']'
            j = code.find(close, i)
            i = n if j < 0 else j + len(close)
            continue
        quote = code[i]
        if quote in '\'"':
            j, out = i + 1, []
            while j < n and code[j] != quote and code[j] != '\n':
                if code[j] == '\\' and j + 1 < n:
                    out.append(code[j + 1]); j += 2
                else:
                    out.append(code[j]); j += 1
            yield ''.join(out)
            i = j + 1
            continue
        i += 1


def wanted_names() -> set[str]:
    names: set[str] = set()
    for source in sorted(ADDON.glob('*.lua')):
        if source.name in SKIP:
            continue
        for value in lua_strings(source.read_text(encoding='utf-8')):
            if value.strip() == value and 3 <= len(value) <= 60:
                names.add(value)
    return names


def lua(value: str) -> str:
    return "'" + value.replace('\\', '\\\\').replace("'", "\\'") + "'"


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument('--build', default='1.60.1.70888')
    parser.add_argument('--cache', type=Path)
    args = parser.parse_args()
    english = table(args.build, 'enUS', args.cache)
    chinese = table(args.build, 'zhCN', args.cache)
    # Count how often each Chinese spelling belongs to each English name. A few
    # client rows are mislabeled (one Fire Vulnerability row carries Curse of
    # Agony's name), so a spelling is kept only for the English name that uses
    # it most; it can never alias two different catalog entries.
    uses: dict[str, dict[str, int]] = {}
    for spell, name in english.items():
        localized = chinese.get(spell)
        if localized and localized != name and re.search(r'[一-鿿]', localized):
            owners = uses.setdefault(localized, {})
            owners[name] = owners.get(name, 0) + 1
    byName: dict[str, set[str]] = {}
    for localized, owners in uses.items():
        best = max(owners.values())
        winners = [name for name, n in owners.items() if n == best]
        if len(winners) == 1:
            byName.setdefault(winners[0], set()).add(localized)
    names = sorted(name for name in wanted_names() if name in byName)
    lines = [
        '-- Generated by scripts/import_spell_names.py from the Forever client',
        f'-- SpellName tables (build {args.build}, enUS and zhCN). Names only, no',
        '-- spell IDs: discovery still matches what the player has learned.',
        'local _, NS = ...',
        'NS.SpellAliases = {',
    ]
    for name in names:
        lines.append(f'    [{lua(name)}]={{{",".join(lua(v) for v in sorted(byName[name]))}}},')
    lines.append('}')
    OUTPUT.write_text('\n'.join(lines) + '\n', encoding='utf-8')
    print(f'wrote {len(names)} names to {OUTPUT.relative_to(ROOT)}')


if __name__ == '__main__':
    main()
